'use strict';
// The outputs of the Pro tools, as plain functions on the data of src/core/access.js (no vscode, so the unit tests
// run them): CSV and JSON text, CREATE TABLE statements in four SQL dialects, a SQLite database file (sql.js, MIT,
// vendored in lib/), and the comparison of two databases.
const path = require('path');
const V = require('./values');

// ---------- CSV and JSON ----------

/** CSV text of one table read by access.readTable: a header line, then one line per row, CRLF line ends. */
function toCsv(table) {
  const lines = [table.columns.map((c) => V.csvField(c.name, 'text')).join(',')];
  for (const r of table.rows) lines.push(r.map((v, i) => V.csvField(v, table.columns[i].type)).join(','));
  return lines.join('\r\n') + '\r\n';
}

/**
 * Rows as JSON objects (column name to value). Each row has no prototype and own data properties, so a column named
 * __proto__ or constructor is a plain key. Use tableJson or toJsonDoc for text: they keep the column order.
 */
function toObjects(table) {
  return table.rows.map((r) => {
    const o = Object.create(null);
    table.columns.forEach((c, i) => { Object.defineProperty(o, c.name, { value: V.jsonValue(r[i], c.type), enumerable: true, writable: true, configurable: true }); });
    return o;
  });
}

/** Rows as Maps (column name to value), in column order. */
function toRowMaps(table) {
  return table.rows.map((r) => new Map(table.columns.map((c, i) => [c.name, V.jsonValue(r[i], c.type)])));
}

/**
 * JSON text with 2-space indents, as JSON.stringify(value, null, 2). A Map is written as an object with its keys in
 * insertion order. Plain objects do not keep that order for names like "2024" and lose a key named __proto__.
 */
function jsonText(value, pad = '') {
  const inner = pad + '  ';
  if (value instanceof Map) {
    const parts = [];
    for (const [k, v] of value) { if (v !== undefined) parts.push(`${inner}${JSON.stringify(String(k))}: ${jsonText(v, inner)}`); }
    return parts.length ? `{\n${parts.join(',\n')}\n${pad}}` : '{}';
  }
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    return `[\n${value.map((v) => inner + (v === undefined ? 'null' : jsonText(v, inner))).join(',\n')}\n${pad}]`;
  }
  const t = JSON.stringify(value, null, 2);
  return t === undefined ? 'null' : t.replace(/\n/g, '\n' + pad);
}

/** JSON text of one table: an array of rows, keys in column order. */
function tableJson(table) {
  return jsonText(toRowMaps(table)) + '\n';
}

/** One JSON document for several tables: { source, tables: { name: [rows] } }, tables and columns in order. */
function toJsonDoc(source, tables) {
  const all = new Map();
  for (const t of tables) all.set(t.name, toRowMaps(t.data));
  return jsonText(new Map([['source', source], ['tables', all]])) + '\n';
}

/** A file name for a table that every file system accepts. */
function safeName(name) {
  const s = String(name).replace(/[\\/:*?"<>|\u0000-\u001f]/g, '_').replace(/^\.+/, '_').trim();
  return (s || 'table').slice(0, 120);
}

/**
 * safeName for every table, made unique without regard to letter case (macOS and Windows file systems): a later
 * name that would clash gets " (2)", " (3)" and so on.
 */
function uniqueFileNames(names) {
  const used = new Set();
  return names.map((n) => {
    const base = safeName(n);
    let name = base;
    for (let k = 2; used.has(name.toLowerCase()); k++) name = `${base} (${k})`;
    used.add(name.toLowerCase());
    return name;
  });
}

// ---------- SQL DDL ----------

const DIALECTS = {
  sqlite: { label: 'SQLite', q: (n) => `"${String(n).replace(/"/g, '""')}"` },
  postgres: { label: 'PostgreSQL', q: (n) => `"${String(n).replace(/"/g, '""')}"` },
  mysql: { label: 'MySQL', q: (n) => `\`${String(n).replace(/`/g, '``')}\`` },
  sqlserver: { label: 'SQL Server', q: (n) => `[${String(n).replace(/]/g, ']]')}]` },
};

/** The SQL type of an Access column in a dialect, with AutoNumber handled the way each dialect allows. */
function sqlType(c, dialect, jet3) {
  const n = V.textChars(c, jet3);
  const p = c.precision || 18, s = c.scale || 0;
  const auto = c.type === 'long' && c.autoLong;
  switch (dialect) {
    case 'sqlite':
      return ({ text: 'TEXT', memo: 'TEXT', byte: 'INTEGER', integer: 'INTEGER', long: 'INTEGER', float: 'REAL', double: 'REAL', currency: 'NUMERIC', numeric: 'NUMERIC',
        datetime: 'TEXT', datetimextended: 'TEXT', boolean: 'INTEGER', binary: 'BLOB', ole: 'BLOB', repid: 'TEXT', bigint: 'INTEGER', complex: 'TEXT' })[c.type] || 'TEXT';
    case 'postgres':
      if (auto) return 'integer GENERATED BY DEFAULT AS IDENTITY';
      return ({ text: `varchar(${n})`, memo: 'text', byte: 'smallint', integer: 'smallint', long: 'integer', float: 'real', double: 'double precision', currency: 'numeric(19,4)',
        numeric: `numeric(${p},${s})`, datetime: 'timestamp', datetimextended: 'timestamp(6)', boolean: 'boolean', binary: 'bytea', ole: 'bytea', repid: 'uuid', bigint: 'bigint', complex: 'text' })[c.type] || 'text';
    case 'mysql':
      if (auto) return 'INT AUTO_INCREMENT UNIQUE';
      return ({ text: `VARCHAR(${n})`, memo: 'LONGTEXT', byte: 'TINYINT UNSIGNED', integer: 'SMALLINT', long: 'INT', float: 'FLOAT', double: 'DOUBLE', currency: 'DECIMAL(19,4)',
        numeric: `DECIMAL(${p},${s})`, datetime: 'DATETIME', datetimextended: 'DATETIME(6)', boolean: 'TINYINT(1)', binary: `VARBINARY(${c.size || 255})`, ole: 'LONGBLOB', repid: 'CHAR(38)', bigint: 'BIGINT', complex: 'LONGTEXT' })[c.type] || 'LONGTEXT';
    case 'sqlserver':
      if (auto) return 'INT IDENTITY(1,1)';
      return ({ text: `NVARCHAR(${n})`, memo: 'NVARCHAR(MAX)', byte: 'TINYINT', integer: 'SMALLINT', long: 'INT', float: 'REAL', double: 'FLOAT', currency: 'MONEY',
        numeric: `DECIMAL(${p},${s})`, datetime: 'DATETIME2(0)', datetimextended: 'DATETIME2(7)', boolean: 'BIT', binary: `VARBINARY(${c.size || 255})`, ole: 'VARBINARY(MAX)', repid: 'UNIQUEIDENTIFIER', bigint: 'BIGINT', complex: 'NVARCHAR(MAX)' })[c.type] || 'NVARCHAR(MAX)';
    default: throw new Error(`Unknown SQL dialect ${dialect}`);
  }
}

/** CREATE TABLE statement of one table entry (access.tableInfo). */
function createTable(t, dialect, jet3) {
  const d = DIALECTS[dialect];
  const cols = t.columns.map((c) => {
    const auto = c.type === 'long' && c.autoLong;
    const notNull = !c.nullable || (auto && dialect !== 'sqlite');
    const notes = [];
    if (auto && dialect === 'sqlite') notes.push('AutoNumber');
    if (c.type === 'complex') notes.push('attachment or multi-value field in Access');
    if (c.type === 'ole') notes.push('OLE Object in Access');
    return `  ${d.q(c.name)} ${sqlType(c, dialect, jet3)}${notNull ? ' NOT NULL' : ''}${notes.length ? ` /* ${notes.join(', ')} */` : ''}`;
  });
  return `CREATE TABLE ${d.q(t.name)} (\n${cols.join(',\n')}\n);`;
}

/** The DDL file for a database: a short header, then one CREATE TABLE per readable user table. */
function toDdl(db, fileName, dialect) {
  const d = DIALECTS[dialect];
  if (!d) throw new Error(`Unknown SQL dialect ${dialect}`);
  const jet3 = db.info.code === 0;
  const ok = db.tables.filter((t) => !t.error);
  const bad = db.tables.filter((t) => t.error);
  const head = [
    `-- Schema of ${fileName} (${db.info.ace ? 'ACCDB' : 'MDB'}, ${db.info.label}), ${d.label} dialect.`,
    `-- ${ok.length} ${ok.length === 1 ? 'table' : 'tables'}. Indexes, keys and relationships are not included. Text sizes are in characters.`,
  ];
  if (bad.length) head.push(`-- Left out (could not be read): ${bad.map((t) => t.name).join(', ')}`);
  return `${head.join('\n')}\n\n${ok.map((t) => createTable(t, dialect, jet3)).join('\n\n')}\n`;
}

// ---------- SQLite ----------

let sqlPromise = null;
/** Loads sql.js (lib/sql-wasm.js and lib/sql-wasm.wasm) once. */
function loadSql() {
  if (!sqlPromise) {
    const lib = path.join(__dirname, '..', '..', 'lib');
    const init = require(path.join(lib, 'sql-wasm.js'));
    sqlPromise = init({ locateFile: (f) => path.join(lib, f) });
  }
  return sqlPromise;
}

/** The value bound into SQLite for an Access value. */
function sqliteValue(v, type) {
  if (v === null || v === undefined || v === V.UNREAD) return null;
  if (typeof v === 'boolean') return v ? 1 : 0;
  if (typeof v === 'bigint') return Number.isSafeInteger(Number(v)) ? Number(v) : v.toString();
  if (v instanceof Date) return V.dateIso(v).replace('T', ' ');
  if (V.isBytes(v)) return new Uint8Array(v);
  if (V.isAttachments(v)) return v.map((a) => a.name).join('; ');
  if (type === 'datetimextended') return V.extDateText(v);
  if (type === 'currency' || type === 'numeric') { const n = Number(v); return Number.isFinite(n) ? n : String(v); }
  return v;
}

/**
 * Builds a SQLite database with every readable user table and its rows. read(name) returns access.readTable(...).
 * Attachments go to a side table "<table>__attachments" (row number, column, file name, type, bytes).
 * Returns { bytes (Uint8Array), tables: [{ name, rows, attachments }], skipped: [{ name, reason }] }.
 */
async function toSqlite(db, read) {
  const SQL = await loadSql();
  const out = new SQL.Database();
  const jet3 = db.info.code === 0;
  const q = DIALECTS.sqlite.q;
  const done = [], skipped = [];
  try {
    out.run('PRAGMA journal_mode = OFF');
    for (const t of db.tables) {
      if (t.error) { skipped.push({ name: t.name, reason: t.error }); continue; }
      let data;
      try { data = read(t.name); } catch (e) { skipped.push({ name: t.name, reason: String((e && e.message) || e) }); continue; }
      out.run('BEGIN');
      out.run(createTable(t, 'sqlite', jet3));
      const cols = t.columns;
      const ins = out.prepare(`INSERT INTO ${q(t.name)} (${cols.map((c) => q(c.name)).join(', ')}) VALUES (${cols.map(() => '?').join(', ')})`);
      let attach = null, nAttach = 0;
      data.rows.forEach((r, ri) => {
        ins.run(r.map((v, i) => sqliteValue(v, cols[i].type)));
        r.forEach((v, i) => {
          if (!V.isAttachments(v) || !v.length) return;
          if (!attach) {
            out.run(`CREATE TABLE ${q(`${t.name}__attachments`)} ("row" INTEGER NOT NULL, "column" TEXT NOT NULL, "file_name" TEXT, "file_type" TEXT, "data" BLOB)`);
            attach = out.prepare(`INSERT INTO ${q(`${t.name}__attachments`)} VALUES (?, ?, ?, ?, ?)`);
          }
          for (const a of v) { attach.run([ri + 1, cols[i].name, a.name || '', a.type || '', a.data ? new Uint8Array(a.data) : null]); nAttach++; }
        });
      });
      ins.free();
      if (attach) attach.free();
      out.run('COMMIT');
      done.push({ name: t.name, rows: data.rows.length, attachments: nAttach });
    }
    return { bytes: out.export(), tables: done, skipped };
  } finally {
    out.close();
  }
}

/** Reads back a SQLite file (the result panel and the tests): table names and row counts. */
async function sqliteCounts(bytes) {
  const SQL = await loadSql();
  const d = new SQL.Database(bytes);
  try {
    const names = (d.exec("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")[0] || { values: [] }).values.map((v) => v[0]);
    return names.map((n) => ({ name: n, rows: Number(d.exec(`SELECT COUNT(*) FROM "${n.replace(/"/g, '""')}"`)[0].values[0][0]) }));
  } finally { d.close(); }
}

// ---------- Compare two databases ----------

const key = (s) => String(s).toLowerCase();

/** Tables, columns and row counts of two databases (access.open results). Names match without case, as in Access. */
function compare(a, b) {
  const mapA = new Map(a.tables.map((t) => [key(t.name), t]));
  const mapB = new Map(b.tables.map((t) => [key(t.name), t]));
  const onlyA = a.tables.filter((t) => !mapB.has(key(t.name))).map((t) => ({ name: t.name, rows: t.rows }));
  const onlyB = b.tables.filter((t) => !mapA.has(key(t.name))).map((t) => ({ name: t.name, rows: t.rows }));
  const jetA = a.info.code === 0, jetB = b.info.code === 0;
  const both = [];
  for (const ta of a.tables) {
    const tb = mapB.get(key(ta.name));
    if (!tb) continue;
    const ca = new Map(ta.columns.map((c) => [key(c.name), c]));
    const cb = new Map(tb.columns.map((c) => [key(c.name), c]));
    const colsOnlyA = ta.columns.filter((c) => !cb.has(key(c.name))).map((c) => c.name);
    const colsOnlyB = tb.columns.filter((c) => !ca.has(key(c.name))).map((c) => c.name);
    const typeChanged = [];
    for (const c of ta.columns) {
      const d = cb.get(key(c.name));
      if (!d) continue;
      const x = V.typeName(c, jetA), y = V.typeName(d, jetB);
      if (x !== y) typeChanged.push({ name: c.name, a: x, b: y });
    }
    const changed = ta.rows !== tb.rows || colsOnlyA.length > 0 || colsOnlyB.length > 0 || typeChanged.length > 0 || !!ta.error !== !!tb.error;
    both.push({ name: ta.name, rowsA: ta.rows, rowsB: tb.rows, colsOnlyA, colsOnlyB, typeChanged, changed, error: ta.error || tb.error || '' });
  }
  both.sort((x, y) => x.name.localeCompare(y.name));
  return { onlyA, onlyB, both, changed: both.filter((x) => x.changed).length, same: both.filter((x) => !x.changed).length };
}

const mdCode = (s) => `\`${String(s).replace(/`/g, "'")}\``;
const signed = (n) => (n > 0 ? `+${n.toLocaleString('en-US')}` : n.toLocaleString('en-US'));

/** The comparison as a Markdown report. */
function compareMarkdown(r, nameA, nameB) {
  const L = [`# Access database comparison`, '', `- A: ${mdCode(nameA)}`, `- B: ${mdCode(nameB)}`, '',
    `${r.onlyA.length} ${r.onlyA.length === 1 ? 'table' : 'tables'} only in A, ${r.onlyB.length} only in B, ${r.changed} changed, ${r.same} the same.`, ''];
  L.push(`## Tables only in A (${r.onlyA.length})`, '');
  if (r.onlyA.length) for (const t of r.onlyA) L.push(`- ${mdCode(t.name)} (${t.rows.toLocaleString('en-US')} rows)`); else L.push('None.');
  L.push('', `## Tables only in B (${r.onlyB.length})`, '');
  if (r.onlyB.length) for (const t of r.onlyB) L.push(`- ${mdCode(t.name)} (${t.rows.toLocaleString('en-US')} rows)`); else L.push('None.');
  L.push('', `## Tables in both (${r.both.length})`, '', '| Table | Rows in A | Rows in B | Difference | Columns only in A | Columns only in B | Type changes |', '|---|---:|---:|---:|---|---|---|');
  for (const t of r.both) {
    L.push(`| ${t.name.replace(/\|/g, '\\|')} | ${t.rowsA.toLocaleString('en-US')} | ${t.rowsB.toLocaleString('en-US')} | ${signed(t.rowsB - t.rowsA)} | ${t.colsOnlyA.join(', ').replace(/\|/g, '\\|')} | ${t.colsOnlyB.join(', ').replace(/\|/g, '\\|')} | ${t.typeChanged.map((x) => `${x.name}: ${x.a} to ${x.b}`).join('; ').replace(/\|/g, '\\|')} |`);
  }
  L.push('');
  return L.join('\n');
}

